'  $("new-playlist-name").focus();',
'});',
'$("new-playlist-cancel").addEventListener("click", function () {',
'  $("new-playlist-modal").classList.add("hidden");',
'});',

'/* ---------- Track menu (add to playlist / edit / delete) ---------- */',
'var menuTrack = null;',
'function openTrackMenu(track) {',
'  menuTrack = track;',
'  var list = $("track-menu-list");',
'  list.replaceChildren();',

'  var addItem = document.createElement("button");',
'  addItem.className = "modal-list-item";',
'  addItem.innerHTML = ICONS.playlist + "<span style=\\"margin-left:10px;flex:1\\">\u0414\u043e\u0431\u0430\u0432\u0438\u0442\u044c \u0432 \u043f\u043b\u0435\u0439\u043b\u0438\u0441\u0442</span>";',
