'    if (!res.ok) return null;',
'    var data = await res.json();',
'    var item = data.results && data.results[0];',
'    if (!item || !item.artworkUrl100) return null;',
'    var url = item.artworkUrl100.replace("100x100bb", "600x600bb");',
'    var imgRes = await fetch(url);',
'    if (!imgRes.ok) return null;',
'    return await imgRes.blob();',
'  } catch (e) { return null; }',
'}',

