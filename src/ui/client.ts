'    item.textContent = pl.name;',
'    item.addEventListener("click", async function () {',
'      var res = await fetch("/api/playlists/" + encodeURIComponent(pl.id) + "/tracks", {',
'        method: "POST",',
'        headers: { "Content-Type": "application/json" },',
'        body: JSON.stringify({ track_id: track.id })',
'      });',
'      $("add-to-playlist-modal").classList.add("hidden");',
'      if (res.ok) toast("\u0414\u043e\u0431\u0430\u0432\u043b\u0435\u043d\u043e \u0432 \u00ab" + pl.name + "\u00bb");',
'      else toast("\u041e\u0448\u0438\u0431\u043a\u0430");',
'    });',
'    list.appendChild(item);',
'  });',
'  $("add-to-playlist-modal").classList.remove("hidden");',
'}',
'$("add-to-playlist-backdrop").addEventListener("click", function () {',
'  $("add-to-playlist-modal").classList.add("hidden");',
'});',

'/* ---------- Search ---------- */',
'$("search-input").addEventListener("input", function () {',
'  state.search = this.value.trim().toLowerCase();',
'  renderSearch();',
'});',

'function renderSearch() {',
'  var results = $("search-results");',
'  results.replaceChildren();',
'  if (!state.search) {',
'    results.appendChild(emptyState("search", "\u041d\u0430\u0439\u0434\u0438 \u0442\u0440\u0435\u043a, \u0438\u0441\u043f\u043e\u043b\u043d\u0438\u0442\u0435\u043b\u044f \u0438\u043b\u0438 \u0430\u043b\u044c\u0431\u043e\u043c"));',
'    return;',
'  }',
'  var matches = state.tracks.filter(function (t) {',
'    var hay = (t.title + " " + trackArtist(t) + " " + trackAlbum(t)).toLowerCase();',
'    return hay.indexOf(state.search) !== -1;',
'  });',
'  if (!matches.length) {',
'    results.appendChild(emptyState("search", "\u041d\u0438\u0447\u0435\u0433\u043e \u043d\u0435 \u043d\u0430\u0439\u0434\u0435\u043d\u043e"));',
'    return;',
'  }',
'  matches.forEach(function (track) {',
'    var index = state.tracks.indexOf(track);',
'    results.appendChild(renderTrackRow(track, index, {',
'      list: "library",',
'      onPlay: function () { playFromLibrary(index); }',
'    }));',
'  });',
'}',

'/* ---------- Login / logout ---------- */',
'$("login-form").addEventListener("submit", async function (e) {',
'  e.preventDefault();',
'  var username = $("login-username").value.trim();',
'  var password = $("login-password").value;',
'  $("login-error").classList.add("hidden");',
'  try {',
'    var res = await fetch("/api/auth/login", {',
'      method: "POST",',
'      headers: { "Content-Type": "application/json" },',
'      body: JSON.stringify({ username: username, password: password })',
'    });',
'    if (!res.ok) {',
'      var data = await res.json().catch(function () { return {}; });',
'      setText("login-error", data.error || "\u041e\u0448\u0438\u0431\u043a\u0430 \u0432\u0445\u043e\u0434\u0430");',
'      $("login-error").classList.remove("hidden");',
'      return;',
'    }',
'    await checkAuth();',
'  } catch (e) {',
'    setText("login-error", "\u041d\u0435 \u0443\u0434\u0430\u043b\u043e\u0441\u044c \u043f\u043e\u0434\u043a\u043b\u044e\u0447\u0438\u0442\u044c\u0441\u044f \u043a \u0441\u0435\u0440\u0432\u0435\u0440\u0443");',
'    $("login-error").classList.remove("hidden");',
'  }',
'});',

'async function logout() {',
'  await fetch("/api/auth/logout", { method: "POST" }).catch(function () {});',
'  state.user = null;',
'  state.tracks = [];',
'  state.currentIndex = -1;',
'  audio.pause();',
'  audio.removeAttribute("src");',
'  audio.load();',
'  showLogin();',
'}',
'$("logout-button").addEventListener("click", logout);',
'$("user-button").addEventListener("click", function () { switchView("profile-view"); });',

'$("play-button").addEventListener("click", togglePlay);',
'$("mini-play").addEventListener("click", togglePlay);',
'$("next-button").addEventListener("click", nextTrack);',
'$("mini-next").addEventListener("click", nextTrack);',
'$("prev-button").addEventListener("click", previousTrack);',

'$("shuffle-button").addEventListener("click", function () {',
'  state.shuffle = !state.shuffle;',
