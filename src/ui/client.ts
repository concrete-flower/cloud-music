'function xhrUpload(url, blob, contentType, onProgress) {',
'  return new Promise(function (resolve, reject) {',
'    var xhr = new XMLHttpRequest();',
'    xhr.open("PUT", url);',
'    if (contentType) xhr.setRequestHeader("Content-Type", contentType);',
'    xhr.upload.addEventListener("progress", function (e) {',
'      if (e.lengthComputable && onProgress) onProgress(e.loaded / e.total);',
'    });',
'    xhr.onload = function () {',
'      if (xhr.status >= 200 && xhr.status < 300) resolve(); else reject(new Error("HTTP " + xhr.status));',
'    };',
'    xhr.onerror = function () { reject(new Error("network error")); };',
'    xhr.send(blob);',
'  });',
'}',

'async function parseTags(file) {',
'  try {',
'    var mm = await import("https://esm.sh/music-metadata-browser@2.5.10?bundle");',
'    var meta = await mm.parseBlob(file);',
'    var common = meta.common || {};',
'    var picture = common.picture && common.picture[0];',
'    return {',
'      title: common.title || null,',
'      artist: common.artist || (common.artists && common.artists[0]) || null,',
'      album: common.album || null,',
'      album_artist: common.albumartist || null,',
'      year: common.year || null,',
'      genre: (common.genre && common.genre[0]) || null,',
'      track_number: (common.track && common.track.no) || null,',
'      disc_number: (common.disk && common.disk.no) || null,',
'      duration_seconds: meta.format && meta.format.duration ? Math.round(meta.format.duration) : null,',
'      cover: picture ? new Blob([picture.data], { type: picture.format || "image/jpeg" }) : null',
'    };',
'  } catch (e) {',
'    console.warn("tag parsing unavailable", e);',
'    return null;',
'  }',
'}',

'async function fetchFallbackCover(artist, title) {',
